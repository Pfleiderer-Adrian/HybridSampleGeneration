PROJECT=Path('/workspaces/hybrid-sample-generator')
LEGACY=Path('/mnt/results/mvtec2/experiments/anomalydiffusion_v3')
BASE=Path('/mnt/results/mvtec2/model_cache/anomalydiffusion/model.ckpt')
CATEGORIES=['can','fabric','fruit_jelly','rice','sheet_metal','vial','wallplugs','walnuts']
STEPS=50000
MILESTONES=[10000,20000,30000,40000,50000]


def centers(lo,hi):
    if hi-lo<=128:return [(lo+hi)//2]
    result=list(range(lo+64,hi-64+1,64))
    if result[-1]!=hi-64:result.append(hi-64)
    return result


def prepare(output):
    from scipy.ndimage import label,find_objects
    from .prepare import sha256
    output.mkdir(parents=True,exist_ok=False)
    base_hash=sha256(BASE)
    plan=dict(experiment='ad_scale2x_50k_v1',created_utc=datetime.now(timezone.utc).isoformat(),gpus=[1],
        base_checkpoint=str(BASE),base_checkpoint_sha256=base_hash,steps=STEPS,milestones=MILESTONES,
        source_snapshot=str(output/'source_snapshot'),jobs=[],
        generation=dict(checkpoint='last',checkpoint_step=STEPS,adaptive_attention=True,scale=2,
            ddim_steps=200,ddim_eta=1.,spatial_encoder_mode='eval',
            diagnostic_mask_source='provided final frozen V3 hybrid mask, exact healthy partner',
            production_pool='not regenerated by this training queue'),
        checkpoint_policy=dict(last=True,best=True,monitor='val/loss_simple_ema',mode='min',
            milestones=MILESTONES,compact=True,frozen_base_by_sha256=True),
        batch_size=4,seed=42,effective_learning_rate=.02,early_stopping=False,
        oversized_components='128px windows at64px stride, anchored to component bbox, all positive pixels covered')
    for cat in CATEGORIES:
        legacy=LEGACY/cat;root=output/cat;folder=root/'centered_2x/inputs';folder.mkdir(parents=True)
        split=json.loads((legacy/'split_manifest.json').read_text());old_protocol=json.loads((legacy/'protocol.json').read_text())
        rows_by_part={};stats={};train_ids=set()
        for part,stem in [('train','training'),('validation','validation')]:
            rows=[];components=large=missing=source_pixels=0;image_ids=[];occupancies=[]
            for sample in split['partitions'][part]:
                if sample['label']=='good':continue
                image=np.asarray(Image.open(sample['image_path']).convert('RGB'))
                mask=np.asarray(Image.open(sample['mask_path']).convert('L'))>0
                if not mask.any() or image.shape[:2]!=mask.shape:raise ValueError('Invalid source mask.')
                lab,n=label(mask);components+=n;seen=set();coverage=np.zeros_like(mask)
                image_hash,mask_hash=sha256(sample['image_path']),sha256(sample['mask_path'])
                for component,region in enumerate(find_objects(lab),start=1):
                    h,w=region[0].stop-region[0].start,region[1].stop-region[1].start
                    large+=max(h,w)>128
                    for cy in centers(region[0].start,region[0].stop):
                        for cx in centers(region[1].start,region[1].stop):
                            support,_=centered(lab==component,cx,cy,128)
                            if not support.any() or (cx,cy) in seen:continue
                            seen.add((cx,cy));native_mask,crop=centered(mask,cx,cy,128);native_image,_=centered(image,cx,cy,128)
                            out_image=Image.fromarray(native_image).resize((256,256),Image.Resampling.BICUBIC)
                            out_mask=Image.fromarray(native_mask.astype('uint8')*255).resize((256,256),Image.Resampling.NEAREST)
                            condition=np.asarray(out_mask)>0
                            if int(condition.sum())!=int(native_mask.sum())*4:raise ValueError('Mask scaling lost foreground.')
                            x,y,_,_=crop;x0,y0=max(x,0),max(y,0);x1,y1=min(x+128,mask.shape[1]),min(y+128,mask.shape[0])
                            coverage[y0:y1,x0:x1]=True
                            index=f'{stem}_{len(rows):06d}';patchfolder=folder/'patches';patchfolder.mkdir(exist_ok=True)
                            ip,mp=patchfolder/f'{index}_image.png',patchfolder/f'{index}_mask.png';out_image.save(ip);out_mask.save(mp)
                            occupancies.append(float(condition.reshape(32,8,32,8).max((1,3)).mean()))
                            rows.append(dict(sample_id=sample['sample_id'],label='bad',image_path=str(ip),mask_path=str(mp),
                                crop_xywh=crop,native_positive_pixels=int(native_mask.sum()),scale=2,source_component=component,
                                source_image_sha256=image_hash,source_mask_sha256=mask_hash))
                lost=int(np.count_nonzero(mask & ~coverage));missing+=lost;source_pixels+=int(mask.sum());image_ids.append(sample['sample_id'])
                if lost:raise ValueError(f'Uncovered mask pixels in {cat}/{sample["sample_id"]}: {lost}')
            ids=set(image_ids)
            if part=='train':train_ids=ids
            elif train_ids & ids:raise ValueError('Train/validation overlap.')
            if not rows:raise ValueError('Empty prepared partition.')
            stats[part]=dict(images=len(ids),components=components,oversized_components=large,patches=len(rows),
                uncovered_native_mask_pixels=missing,source_mask_pixels=source_pixels,mean_latent_mask_fraction=float(np.mean(occupancies)))
            rows_by_part[part]=rows
            write(folder/f'{stem}_patches.json',dict(version=1,category=cat,split_fingerprint=split['fingerprint'],
                upstream_commit=old_protocol['upstream_commit'],resolution='centered_128_to256_scale2',rows=rows))
        write(folder/'split_manifest.json',split)
        protocol=dict(old_protocol);protocol.update(experiment=plan['experiment'],appearance_steps=STEPS,
            appearance_checkpoint_selection='last',adaptive_attention=True,scale=2,mask_steps=None,
            validation_patches_sha256=sha256(folder/'validation_patches.json'),
            adaptations=['Frozen V3 grouped split','Defect-centered native128 windows; overlapping coverage for large components',
                'RGB bicubic2x and binary-mask nearest2x','Maxpool32 latent support','Fresh appearance weights, unchanged LR0.02',
                'Compact coherent last/best/10k checkpoints; frozen base referenced by SHA256'])
        write(folder/'protocol.json',protocol)
        write(root/'plan.json',dict(experiment=plan['experiment'],category=cat,base_checkpoint_sha256=base_hash,
            steps=STEPS,milestones=MILESTONES,stats=stats,generation=plan['generation'],checkpoint_policy=plan['checkpoint_policy']))
        write(root/'preflight.json',dict(train_validation_disjoint=True,all_masks_binary_nonempty=True,exact_nearest2x=True,
            full_source_mask_coverage=True,stats=stats,split_fingerprint=split['fingerprint']))
        plan['jobs'].append(dict(category=cat,inputs=str(folder),input_sha256={str(p):sha256(p) for p in folder.glob('*.json')},stats=stats))
        print('prepared',cat,stats,flush=True)
    snapshot=output/'source_snapshot';dest=snapshot/'experiments/anomalydiffusion';dest.mkdir(parents=True)
    (snapshot/'experiments/__init__.py').write_text('')
    source=Path(__file__).resolve().parent
    for f in source.glob('*.py'):shutil.copy2(f,dest/f.name)
    for name in ['upstream','.tools']:(dest/name).symlink_to(source/name,target_is_directory=True)
    write(output/'source_snapshot_sha256.json',{str(f.relative_to(snapshot)):sha256(f) for f in snapshot.rglob('*.py') if 'upstream' not in f.parts and '.tools' not in f.parts})
    write(output/'plan.json',plan)


def train(output,cat):
    from .scale_pilot import train as run_train
    from .prepare import sha256
    run_train(output/cat,'centered_2x',category=cat,steps=STEPS,milestones=MILESTONES)
    folder=output/cat/'centered_2x/training';last=folder/'checkpoints/step_050000.pt'
    if not last.is_file():raise ValueError('Missing final50k checkpoint.')
    write(folder/'selection.json',dict(selection='last',training_steps=STEPS,checkpoint=str(last),
        checkpoint_sha256=sha256(last),best=json.loads((folder/'best.json').read_text()),
        generation=dict(adaptive_attention=True,scale=2,spatial_encoder_mode='eval')))


