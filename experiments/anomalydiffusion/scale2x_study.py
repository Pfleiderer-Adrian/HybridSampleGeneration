def preview(output,cat):
    """Only diagnostic paired hybrid masks; no production cache/downstream changes."""
    import torch
    from scipy.ndimage import label,find_objects
    from .run import seed_all,image_array
    from .runtime import load_model
    root=output/cat;dest=root/'preview_last_aar';dest.mkdir(exist_ok=False)
    protocol=json.loads((LEGACY/cat/'protocol.json').read_text());study=Path(protocol['hybrid_study'])
    frozen=json.loads((LEGACY/cat/'hybrid_provenance.json').read_text());split=json.loads((root/'centered_2x/inputs/split_manifest.json').read_text())
    train_ids={r['sample_id'] for r in split['partitions']['train']}
    con=sqlite3.connect(f'file:{study}/artifacts.sqlite?mode=ro',uri=True);con.row_factory=sqlite3.Row
    cases=[];seen=set()
    for source in frozen:
        if source['original_id'] in seen:continue
        h=dict(con.execute('SELECT * FROM hybrid_samples WHERE id=?',(source['hybrid_id'],)).fetchone())
        o=dict(con.execute('SELECT * FROM original_samples WHERE id=?',(source['original_id'],)).fetchone())
        if o['has_anomaly'] or o['source_name'] not in train_ids:raise ValueError('Wrong diagnostic control split.')
        mask=np.any(np.load(study/h['segmentation_path'],allow_pickle=False)>0,axis=0)
        lab,n=label(mask);sizes=np.bincount(lab.ravel());sizes[0]=0;component=int(np.argmax(sizes));region=find_objects(lab)[component-1]
        cy=(region[0].start+region[0].stop)//2;cx=(region[1].start+region[1].stop)//2
        support,_=centered(lab==component,cx,cy,128)
        if not support.any():
            ys,xs=np.nonzero(lab==component);j=int(np.argmin((ys-cy)**2+(xs-cx)**2));cy,cx=int(ys[j]),int(xs[j])
        native_mask,crop=centered(mask,cx,cy,128);i=len(cases)
        for name,arr in [('healthy',np.load(study/o['image_path'],allow_pickle=False)),('hybrid',np.load(study/h['image_path'],allow_pickle=False))]:
            arr=np.clip(arr.transpose(1,2,0),0,255).round().astype('uint8')
            if arr.shape[2]==1:arr=np.repeat(arr,3,axis=2)
            patch,_=centered(arr,cx,cy,128)
            Image.fromarray(patch).resize((256,256),Image.Resampling.BICUBIC).save(dest/f'{i:02}_{name}.png')
        Image.fromarray(native_mask.astype('uint8')*255).resize((256,256),Image.Resampling.NEAREST).save(dest/f'{i:02}_mask.png')
        cases.append(dict(index=i,provenance=source,control_sample_id=o['source_name'],crop_xywh=crop,largest_component_pixels=int(sizes[component]),
            full_component_inside=bool(region[0].start>=crop[1] and region[0].stop<=crop[1]+128 and region[1].start>=crop[0] and region[1].stop<=crop[0]+128)))
        seen.add(source['original_id'])
        if len(cases)==4:break
    con.close()
    if len(cases)!=4:raise ValueError('Expected four diagnostic cases.')
    seed_all(42);model,_=load_model('appearance',BASE,dest/'work',cat,'maxpool')
    selection=json.loads((root/'centered_2x/training/selection.json').read_text());state=torch.load(selection['checkpoint'],map_location='cpu')
    expected={k for k in model.state_dict() if k.startswith('embedding_manager.')}
    if set(state['learned_state_dict'])!=expected or state['step']!=STEPS:raise ValueError('Wrong final checkpoint.')
    model.load_state_dict(state['learned_state_dict'],strict=False);model.eval();seed_all(62000)
    batch=dict(image=torch.from_numpy(np.stack([image_array(dest/f'{i:02}_healthy.png') for i in range(4)])).cuda(),
        mask=torch.from_numpy(np.stack([np.asarray(Image.open(dest/f'{i:02}_mask.png').convert('L'))>0 for i in range(4)]).astype('float32')).cuda(),
        caption=['a photo of a *']*4,name=[f'{cat}+bad']*4)
    with torch.no_grad():logs=model.log_images(batch,N=4,sample=False,inpaint=True,unconditional_only=True,ddim_steps=200,ddim_eta=1.,adaptive_mask=True)
    for i in range(4):
        value=logs['samples_inpainting'][i].detach().cpu().permute(1,2,0).numpy()
        if not np.isfinite(value).all():raise ValueError('Nonfinite diagnostic output.')
        Image.fromarray(np.clip((value+1)*127.5,0,255).round().astype('uint8')).save(dest/f'{i:02}_ad.png')
    write(dest/'results.json',dict(category=cat,cases=cases,checkpoint=selection,aar=True,scale=2,seed=62000,ddim_steps=200,diagnostic_only=True))


