def queue(output):
    from .prepare import sha256
    plan=json.loads((output/'plan.json').read_text());snapshot=Path(plan['source_snapshot'])
    env=dict(os.environ);env.update(CUDA_VISIBLE_DEVICES='1',PYTHONPATH=str(snapshot),PYTHONUNBUFFERED='1',OMP_NUM_THREADS='8',MKL_NUM_THREADS='8',OPENBLAS_NUM_THREADS='8',TOKENIZERS_PARALLELISM='false',
        LD_LIBRARY_PATH=str(PROJECT/'experiments/anomalydiffusion/.tools/cuda')+(':'+env['LD_LIBRARY_PATH'] if env.get('LD_LIBRARY_PATH') else ''))
    python=PROJECT/'experiments/anomalydiffusion/.venv/bin/python'
    state=dict(pid=os.getpid(),status='running',started_utc=datetime.now(timezone.utc).isoformat(),gpus=[1],categories=CATEGORIES,profile=plan['experiment'])
    write(output/'status.json',state);failed=[]
    for job in plan['jobs']:
        cat=job['category'];folder=output/'jobs'/cat;folder.mkdir(parents=True);jobstate=dict(category=cat,gpu=1,pid=os.getpid(),status='running',stages=[])
        try:
            for path,digest in job['input_sha256'].items():
                if sha256(path)!=digest:raise ValueError('Prepared input changed.')
            for action in ['train','preview']:
                stage='appearance_training' if action=='train' else 'generation_preview'
                cmd=[str(python),'-m','experiments.anomalydiffusion.scale2x_study',action,'--output',str(output),'--category',cat]
                entry=dict(stage=stage,status='running',started_utc=datetime.now(timezone.utc).isoformat(),command=cmd,log=str(folder/f'{action}.log'))
                jobstate.update(stage=stage,updated_utc=datetime.now(timezone.utc).isoformat());jobstate['stages'].append(entry)
                with Path(entry['log']).open('w') as log:
                    child=subprocess.Popen(cmd,env=env,cwd=snapshot,stdout=log,stderr=subprocess.STDOUT);entry['pid']=child.pid;write(folder/'status.json',jobstate)
                    plotted=0.
                    while child.poll() is None:
                        if time.monotonic()-plotted>=60:
                            try:plot(output,cat)
                            except Exception as error:write(folder/'plot_warning.json',dict(error=str(error)))
                            plotted=time.monotonic()
                        time.sleep(5)
                    rc=child.returncode
                entry.update(status='complete' if rc==0 else 'failed',returncode=rc,finished_utc=datetime.now(timezone.utc).isoformat());write(folder/'status.json',jobstate)
                if rc:raise RuntimeError(f'{cat}/{action} exited with{rc}')
                plot(output,cat)
                if action=='preview':plot_preview(output,cat)
            jobstate.update(status='complete',finished_utc=datetime.now(timezone.utc).isoformat())
        except Exception as error:
            jobstate.update(status='failed',error=str(error),traceback=traceback.format_exc());failed.append(cat)
        write(folder/'status.json',jobstate)
    state.update(status='failed' if failed else 'complete',failed_categories=failed,finished_utc=datetime.now(timezone.utc).isoformat());write(output/'status.json',state)


def main():
    p=argparse.ArgumentParser();p.add_argument('action',choices=['prepare','train','preview','plot','queue']);p.add_argument('--output',type=Path,required=True);p.add_argument('--category',choices=CATEGORIES);a=p.parse_args()
    output=a.output.resolve()
    if Path('/mnt/results') not in output.parents:raise ValueError('This study belongs in the Results folder.')
    if a.action=='prepare':prepare(output)
    elif a.action=='train':train(output,a.category)
    elif a.action=='preview':preview(output,a.category)
    elif a.action=='plot':plot(output,a.category);plot_preview(output,a.category)
    else:
        import fcntl
        with (output/'queue.lock').open('a') as lock:
            fcntl.flock(lock,fcntl.LOCK_EX|fcntl.LOCK_NB)
            queue(output)


if __name__=='__main__':main()
